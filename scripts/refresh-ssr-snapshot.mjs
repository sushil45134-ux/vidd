/**
 * Regenerates src/lib/ssrSnapshot.ts from the live Supabase library so the
 * SSR static fallback (shown to no-JS TV browsers) stays representative.
 *
 * Usage:
 *   node scripts/refresh-ssr-snapshot.mjs
 *
 * Picks the first episode of up to 5 distinct series (by playlist/title
 * prefix) from the newest rows, so the snapshot shows variety rather than a
 * wall of consecutive episodes.
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SUPABASE_URL = "https://yjakihgnxntjfjvarxmt.supabase.co";
const SUPABASE_ANON_KEY =
  "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6InlqYWtpaGdueG50amZqdmFyeG10Iiwicm9sZSI6ImFub24iLCJpYXQiOjE3ODQ2MjIwMjQsImV4cCI6MjEwMDE5ODAyNH0.swnTt5ubxf04lkRvaulAhXExdYSAXsRjPuEY1Iv63Do";

const rows = await fetch(
  `${SUPABASE_URL}/rest/v1/movies?select=id,title,image,backdrop,genre,year,rating,youtube_id,embed_url&order=id.desc&limit=200`,
  { headers: { apikey: SUPABASE_ANON_KEY, accept: "application/json" } },
).then((r) => {
  if (!r.ok) throw new Error(`supabase ${r.status}`);
  return r.json();
});

const seriesKey = (r) =>
  String(r.title)
    .replace(/\s*-\s*(Episode|Ep\.?|#)\s*\d+.*$/i, "")
    .trim();
const picked = [];
const seen = new Set();
for (const r of rows) {
  const key = seriesKey(r);
  if (seen.has(key)) continue;
  seen.add(key);
  picked.push(r);
  if (picked.length >= 16) break;
}

const esc = (s) => JSON.stringify(s ?? "");
const entries = picked
  .map((r) => {
    const watch = r.youtube_id
      ? `https://www.youtube.com/watch?v=${r.youtube_id}`
      : r.embed_url || "";
    return [
      "  snap(",
      `    ${Number(r.id)},`,
      `    ${esc(r.title)},`,
      `    ${esc(r.image)},`,
      `    ${esc(r.backdrop || r.image)},`,
      `    ${esc(r.genre ?? [])},`,
      `    ${r.year ?? "null"},`,
      `    ${esc(r.rating)},`,
      `    ${esc(watch)},`,
      "  ),",
    ].join("\n");
  })
  .join("\n");

const out = `import type { SsrMovie } from "./ssrLibrary";

/**
 * Static fallback library embedded at build time.
 *
 * Guarantees that the SSR document ALWAYS carries a real poster library —
 * even when the Supabase query is slow/unreachable from the edge — so no-JS
 * TV browsers (pre-module Tizen/webOS) and crawlers never see an empty
 * "Loading…" shell. Interactive clients replace this with live data on boot.
 *
 * Generated by scripts/refresh-ssr-snapshot.mjs on ${new Date().toISOString()}.
 */
const snap = (
  id: number,
  title: string,
  image: string,
  backdrop: string,
  genre: string[],
  year: number | null,
  rating: string | null,
  watchUrl: string,
): SsrMovie => ({ id, title, image, backdrop, genre, year, rating, watchUrl });

export const SSR_LIBRARY_SNAPSHOT: SsrMovie[] = [
${entries}
];
`;

const target = resolve(dirname(fileURLToPath(import.meta.url)), "../src/lib/ssrSnapshot.ts");
writeFileSync(target, out);
console.log(`wrote ${target} with ${picked.length} series`);
